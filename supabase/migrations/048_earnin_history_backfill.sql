--
-- HOW THE EXPORT MAPS TO THIS TABLE
-- The export only records what moved in/out of checking, so a repayment line is
-- principal AND tip/fee combined. Splitting them matters: the fee is the real
-- cost of leaning on Earnin, and without it the running balance drifts negative
-- (repayments exceed advances by exactly the fees — $1,239.03 across this history).
--
--   • positive amount  → 'advance'  (money drawn, always a round denomination)
--   • negative amount  → 'repay'    (the full debit that left checking)
--                      + 'fee'      (that debit minus the advance it retired)
--
-- A 'fee' adds to the balance like an advance does — it IS money owed to Earnin —
-- so advance + fee - repay nets to zero per cycle. Fees decompose cleanly: 181 of
-- 182 repayments land on a known advance denomination plus a fee under $12, and
-- they cluster on $5.99 and $9.99 (the standard tip / Lightning Speed charges).
--
-- OPENING BALANCE
-- The export starts mid-stream: its earliest rows are repayments for advances
-- drawn before the window. A single opening-balance advance of $1,673.89 on
-- 2021-10-14 accounts for those, so the ledger never dives negative.
--
-- RECONCILIATION — this is the check that validates the whole model:
--   advances  20,840.11
--   fees       1,239.03
--   repaid    22,853.03
--   opening    1,673.89
--   ────────────────────
--   balance      900.00   = exactly what's outstanding today (the 5 advances
--                          since the 2026-07-22 payday settlement)
-- Walking it chronologically the balance never goes negative and touches exactly
-- $0.00 on 2026-07-08 — matching "after every paycheck I'm square with Earnin".
--
-- IDEMPOTENT: every row carries an import_key derived from the export, with a
-- unique index, so re-running this (or importing a future export that overlaps)
-- inserts nothing twice. Manually-logged rows have a NULL key and are untouched.
-- ─────────────────────────────────────────────────────────────────────────────

