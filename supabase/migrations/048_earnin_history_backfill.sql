-- REPAYMENT AMOUNTS ARE NORMALIZED TO PRINCIPAL
-- The export only records what moved in/out of checking, so a repayment line is
-- the advance AND its tip/Lightning-Speed fee combined (e.g. a $150 advance comes
-- back as a $155.99 debit). Imported at face value those fees would compound into
-- a drifting negative balance, since repayments would exceed advances by exactly
-- the fees paid.
--
-- So each repayment is recorded at the advance principal it retired — the fee is
-- dropped, not tracked (1,232.98 across this history). Advances are round
-- denominations, so the match is unambiguous: every repayment lands on a known
-- denomination plus a fee under $12.
--
--   • positive amount  → 'advance'  (recorded as-is)
--   • negative amount  → 'repay'    (recorded at principal, fee stripped)
--
-- OPENING BALANCE
-- The export starts mid-stream: its earliest rows are repayments for advances
-- drawn before the window. A single opening-balance advance of 1,673.95 on
-- 2021-10-14 accounts for those, so the ledger never dives negative.
--
-- STOPS AT 2026-07-10 — advances and repayments from 2026-07-10 onward are already
-- logged by hand in the app, so the last 15 export rows are deliberately skipped
-- to avoid duplicates. The import lands on 2026-07-08, a payday settlement, at a
-- balance of exactly $0.00 — so the hand-logged entries pick up from a clean zero.
--
-- RECONCILIATION:
--   opening     1,673.95
--   advances   18,990.11
--   repaid     20,664.06   (at principal)
--   ────────────────────
--   balance         0.00
-- Walking it chronologically the balance never goes negative — consistent with
-- being square with Earnin after every paycheck.
--
-- IDEMPOTENT: every row carries an import_key derived from the export, with a
-- unique index, so re-running this (or importing a future export that overlaps)
-- inserts nothing twice. Hand-logged rows have a NULL key and are untouched.
-- ─────────────────────────────────────────────────────────────────────────────

